import JSZip from 'jszip';
import { generateProjectCode } from './htmlGenerator';
import { generateReactMuiCode } from './reactMuiGenerator';

/**
 * Converts a base64 Data URL to a Uint8Array binary buffer.
 */
function dataUrlToBinary(dataUrl) {
  const parts = dataUrl.split(',');
  const byteString = atob(parts[1]);
  const mimeType = parts[0].split(':')[1].split(';')[0];
  const extension = mimeType.split('/')[1] || 'png';

  const ab = new ArrayBuffer(byteString.length);
  const ia = new Uint8Array(ab);
  for (let i = 0; i < byteString.length; i++) {
    ia[i] = byteString.charCodeAt(i);
  }
  return { data: ia, extension, mimeType };
}

/**
 * Downloads a Blob directly in the browser.
 */
export function triggerFileDownload(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Creates and downloads a production ZIP bundle:
 * - index.html
 * - styles.css
 * - assets/ (extracted base64 images with rewritten paths)
 */
export async function downloadProjectZip(elements, pageSettings, projectName = 'layoutforge-project') {
  const zip = new JSZip();
  const assetsFolder = zip.folder('assets');

  let imageCounter = 1;
  const processedElements = JSON.parse(JSON.stringify(elements));

  // Extract base64 images into the assets folder
  processedElements.forEach(el => {
    if (el.type === 'image' && el.content?.src && el.content.src.startsWith('data:image')) {
      try {
        const { data, extension } = dataUrlToBinary(el.content.src);
        const filename = `image-${imageCounter}.${extension}`;
        assetsFolder.file(filename, data);
        el.content.src = `./assets/${filename}`;
        imageCounter++;
      } catch (err) {
        console.warn('Failed to extract base64 image:', err);
      }
    }

    if (el.type === 'navbar') {
      if (el.content?.logoUrl && el.content.logoUrl.startsWith('data:image')) {
        try {
          const { data, extension } = dataUrlToBinary(el.content.logoUrl);
          const filename = `logo-${imageCounter}.${extension}`;
          assetsFolder.file(filename, data);
          el.content.logoUrl = `./assets/${filename}`;
          imageCounter++;
        } catch (err) {
          console.warn('Failed to extract navbar logo image:', err);
        }
      }

      if (el.content?.avatarUrl && el.content.avatarUrl.startsWith('data:image')) {
        try {
          const { data, extension } = dataUrlToBinary(el.content.avatarUrl);
          const filename = `avatar-${imageCounter}.${extension}`;
          assetsFolder.file(filename, data);
          el.content.avatarUrl = `./assets/${filename}`;
          imageCounter++;
        } catch (err) {
          console.warn('Failed to extract navbar avatar image:', err);
        }
      }
    }

    if (el.styles?.backgroundImage && el.styles.backgroundImage.startsWith('data:image')) {
      try {
        const { data, extension } = dataUrlToBinary(el.styles.backgroundImage);
        const filename = `bg-${imageCounter}.${extension}`;
        assetsFolder.file(filename, data);
        el.styles.backgroundImage = `./assets/${filename}`;
        imageCounter++;
      } catch (err) {
        console.warn('Failed to extract background image:', err);
      }
    }
  });

  // Generate code with rewritten paths
  const { html, css } = generateProjectCode(processedElements, pageSettings, './assets/');

  zip.file('index.html', html);
  zip.file('styles.css', css);
  zip.file('README.md', `# ${projectName}\n\nGenerated by LayoutForge Studio. Pure semantic, responsive HTML5 and CSS3 with zero external dependencies.\n\nOpen \`index.html\` in any modern browser.`);

  const content = await zip.generateAsync({ type: 'blob' });
  const sanitizedName = projectName.toLowerCase().replace(/[^a-z0-9]+/g, '-') || 'layoutforge';
  triggerFileDownload(content, `${sanitizedName}.zip`);
}

/**
 * Creates and downloads a complete, runnable React + TypeScript + Material UI project bundle.
 */
export async function downloadReactMuiZip(elements, pageSettings, projectName = 'layoutforge-project') {
  const zip = new JSZip();
  const bundle = generateReactMuiCode(elements, pageSettings, projectName);

  zip.file('package.json', bundle.packageJson);
  zip.file('index.html', bundle.indexHtml);
  zip.file('vite.config.ts', bundle.viteConfig);
  zip.file(
    'tsconfig.json',
    JSON.stringify(
      {
        compilerOptions: {
          target: 'ES2020',
          useDefineForClassFields: true,
          lib: ['ES2020', 'DOM', 'DOM.Iterable'],
          module: 'ESNext',
          skipLibCheck: true,
          moduleResolution: 'bundler',
          isolatedModules: true,
          noEmit: true,
          jsx: 'react-jsx',
          strict: true,
          noUnusedLocals: true,
          noUnusedParameters: true,
          noFallthroughCasesInSwitch: true
        },
        include: ['src']
      },
      null,
      2
    )
  );

  const srcFolder = zip.folder('src');
  srcFolder.file('App.tsx', bundle.appTsx);
  srcFolder.file('theme.ts', bundle.themeTs);
  srcFolder.file(
    'main.tsx',
    `import React from 'react';\nimport ReactDOM from 'react-dom/client';\nimport App from './App';\n\nReactDOM.createRoot(document.getElementById('root')!).render(\n  <React.StrictMode>\n    <App />\n  </React.StrictMode>\n);\n`
  );

  zip.file(
    'README.md',
    `# ${projectName}\n\nGenerated with LayoutForge React + Material UI (MUI v5) & TypeScript.\n\n## Quick Start\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`
  );

  const content = await zip.generateAsync({ type: 'blob' });
  const sanitizedName = projectName.toLowerCase().replace(/[^a-z0-9]+/g, '-') || 'layoutforge';
  triggerFileDownload(content, `${sanitizedName}-react-mui.zip`);
}
